// Generates, from tokens.css (the single source of truth):
//   - theme.generated.css : Tailwind v4 @theme mapping so utilities (bg-surface, rounded-lg ...) use tokens
//   - tokens.native.ts    : resolved values for React Native (light + dark)
// `--check` verifies the committed outputs are up to date (used by pnpm verify).
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { THEME_DIR, loadThemes, parseColor, resolve, toRn } from './tokens-lib.mjs';

const check = process.argv.includes('--check');
const { light, dark } = loadThemes();

const names = Object.keys(light);
const camel = (s) => s.replaceAll(/-([a-z0-9])/g, (_, c) => c.toUpperCase());
const strip = (name, prefix) => name.slice(prefix.length);

// ---- Tailwind mapping -------------------------------------------------------------------------
const COLOR_PREFIXES = [
  ['--color-', '--color-'],
  ['--tint-', '--color-tint-'],
  ['--chart-session-', '--color-chart-session-'],
  ['--chart-seq-', '--color-chart-seq-'],
];
const chartSeries = names.filter((n) => /^--chart-[1-6]$/.test(n));

const lines = [];
const map = (twName, tokenName) => lines.push(`  ${twName}: var(${tokenName});`);

lines.push('  --color-*: initial;');
for (const name of names) {
  for (const [from, to] of COLOR_PREFIXES) {
    if (name.startsWith(from)) map(to + strip(name, from), name);
  }
}
for (const name of chartSeries) map(`--color-chart-${name.at(-1)}`, name);
for (const n of ['xs', 'sm', 'md', 'lg', 'xl', 'full']) map(`--radius-${n}`, `--radius-${n}`);
for (const n of ['xs', 'sm', 'md', 'lg']) map(`--shadow-${n}`, `--shadow-${n}`);
for (const n of ['xs', 'sm', 'md', 'lg', 'xl', '2xl', '3xl', '4xl', '5xl'])
  map(`--text-${n}`, `--text-${n}`);
map('--text-base', '--text-md');
for (const n of ['tight', 'snug', 'normal']) map(`--leading-${n}`, `--leading-${n}`);
for (const n of ['tight', 'normal', 'wide']) map(`--tracking-${n}`, `--tracking-${n}`);
for (const n of ['standard', 'emphasized', 'exit']) map(`--ease-${n}`, `--ease-${n}`);
map('--font-sans', '--font-body');
map('--font-display', '--font-display');
map('--font-mono', '--font-mono');
map('--font-urdu', '--font-urdu-body');

const css = `/* GENERATED by scripts/gen-native-tokens.mjs from tokens.css. Do not edit by hand. */
/* Maps token names to Tailwind v4 theme keys. tokens.css stays unlayered so its values win over the
   same-named theme declarations Tailwind emits, and dark mode re-assignments keep working. */
@theme inline {
${lines.join('\n')}
}
`;

// ---- React Native tokens ----------------------------------------------------------------------
function nativeColors(vars) {
  const out = {};
  for (const name of Object.keys(vars)) {
    let key;
    if (name.startsWith('--color-')) key = strip(name, '--color-');
    else if (name.startsWith('--tint-')) key = camel(strip(name, '--'));
    else if (/^--chart-(\d|session-|seq-)/.test(name)) key = strip(name, '--');
    else continue;
    const color = parseColor(resolve(vars, name));
    if (!color) continue; // non-colour tokens in these namespaces are skipped
    // Translucent colours keep their alpha; RN composites them itself.
    out[camel(key)] = toRn(color);
  }
  return out;
}

const px = (value) => {
  const v = value.trim();
  if (v.endsWith('rem')) return Number.parseFloat(v) * 16;
  if (v.endsWith('px')) return Number.parseFloat(v);
  if (v.endsWith('ms')) return Number.parseFloat(v);
  return Number(v);
};
const scalars = (prefix, vars = light) =>
  Object.fromEntries(
    Object.keys(vars)
      .filter((n) => n.startsWith(prefix) && Number.isFinite(px(resolve(vars, n))))
      .map((n) => [camel(strip(n, prefix)), px(resolve(vars, n))]),
  );

const native = {
  color: { light: nativeColors(light), dark: nativeColors(dark) },
  radius: scalars('--radius-'),
  space: scalars('--space-'),
  fontSize: scalars('--text-'),
  fontWeight: Object.fromEntries(
    Object.entries(scalars('--weight-')).map(([k, v]) => [k, String(v)]),
  ),
  duration: scalars('--duration-'),
  size: {
    touchTargetMin: px(light['--touch-target-min']),
    touchTargetNative: px(light['--touch-target-native']),
    touchGapMin: px(light['--touch-gap-min']),
    controlHeightSm: px(light['--control-height-sm']),
    controlHeightMd: px(light['--control-height-md']),
    controlHeightLg: px(light['--control-height-lg']),
    rowHeightComfortable: px(light['--row-height-comfortable']),
    rowHeightCompact: px(light['--row-height-compact']),
  },
};

const ts = `// GENERATED by scripts/gen-native-tokens.mjs from tokens.css. Do not edit by hand.
// Sizes are in dp (rem * 16). Colours are resolved per theme.
export const tokens = ${JSON.stringify(native, null, 2)} as const;

export type ThemeName = keyof typeof tokens.color;
export type ColorToken = keyof typeof tokens.color.light;
`;

// ---- write or check ---------------------------------------------------------------------------
const outputs = [
  ['theme.generated.css', css],
  ['tokens.native.ts', ts],
];
let stale = 0;
for (const [file, content] of outputs) {
  const target = join(THEME_DIR, file);
  if (check) {
    let current = '';
    try {
      current = readFileSync(target, 'utf8');
    } catch {
      // missing file counts as stale
    }
    if (current.replaceAll('\r\n', '\n') !== content) {
      console.error(`STALE ${file}: run \`pnpm gen:tokens\` and commit the result.`);
      stale += 1;
    }
  } else {
    writeFileSync(target, content);
    console.log(`wrote ${file}`);
  }
}
if (check) {
  if (stale > 0) process.exit(1);
  console.log('generated token files are up to date');
}
